export function icon(name, size = 20) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] || P.info}</svg>`;
}

// Иконка за вида опасност
export function hazardIcon(type) {
  if (/accident|jam|breakdown/.test(type)) return 'car';
  if (/closure/.test(type)) return 'ban';
  if (/roadworks|lane_closed/.test(type)) return 'works';
  if (/snow|freez|ice/.test(type)) return 'snow';
  if (/rain|flood/.test(type)) return 'rain';
  if (/storm|thunder/.test(type)) return 'storm';
  if (/wind/.test(type)) return 'wind';
  if (/fog/.test(type)) return 'fog';
  if (/landslide/.test(type)) return 'mountain';
  return 'alert';
}

// <span data-icon="…"> в HTML-а → SVG
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (!el.firstElementChild) el.innerHTML = icon(el.dataset.icon);
  }
}
