def region_of(lat: float, lon: float) -> str:
    best, best_d = "", float("inf")
    for code, (_, anchors) in REGIONS.items():
        for a_lat, a_lon in anchors:
            d = haversine_km(lat, lon, a_lat, a_lon)
            if d < best_d:
                best, best_d = code, d
    return best


def name(code: str) -> str:
    return REGIONS.get(code, (code, []))[0]
